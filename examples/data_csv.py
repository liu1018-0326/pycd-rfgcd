import pandas as pd

def write_lists_to_csv_by_column(lists_data, csv_filename):
    """
    将多个一维列表按列写入CSV文件
    :param lists_data: 列表的列表（每个子列表对应CSV的一列）
    :param csv_filename: 输出CSV文件名（含.csv后缀）
    """
    # 步骤1：将列表数据转换为字典（pandas要求列名为键，列数据为值）
    # 列名默认设为 col_0, col_1, ..., col_n
    df_data = {}
    for idx, single_list in enumerate(lists_data):
        df_data[f"col_{idx}"] = single_list
    
    # 步骤2：创建DataFrame（pandas的核心数据结构，支持按列组织数据）
    df = pd.DataFrame(df_data)
    
    # 步骤3：写入CSV文件（index=False 表示不写入行索引）
    df.to_csv(csv_filename, index=False, encoding='utf-8')
    print(f"数据已成功写入 {csv_filename}")

